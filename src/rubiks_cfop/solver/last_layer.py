"""OLL and PLL: the last layer of CFOP, driven by lookup tables.

Both stages work the same way.  A JSON table lists the cases -- the 57 numbered OLL
cases and the 21 named PLL cases -- each with one algorithm.  Recognition never
needs a hand written pattern description: the pattern of a case is computed from
the case itself, by inverting its algorithm, so the table and the recogniser cannot
drift apart.

Because a case is only defined up to an adjustment of the top face, each case is
stored once per AUF (four entries), which turns recognition into a single
dictionary lookup.

The tables live in ``data/oll.json`` and ``data/pll.json`` and are generated by
``tools/build_last_layer_tables.py`` from a published algorithm collection.  Every
entry is verified: applying its algorithm to its own case state must orient the
last layer (OLL) or solve it (PLL).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from enum import StrEnum
from functools import lru_cache
from pathlib import Path
from typing import TYPE_CHECKING, Final

from rubiks_cfop.cube.cube import Cube
from rubiks_cfop.cube.facelets import SOLVED_FACELETS
from rubiks_cfop.cube.moves import Move, get_move
from rubiks_cfop.cube.notation import format_moves, parse_moves
from rubiks_cfop.errors import InvalidStateError, UnsolvableStateError

if TYPE_CHECKING:
    from rubiks_cfop.cube.cubie import CubieCube

__all__ = [
    "DATA_DIR",
    "LastLayerCase",
    "LastLayerKind",
    "LastLayerResult",
    "LastLayerTable",
    "load_oll_table",
    "load_pll_table",
    "oll_pattern",
    "pll_pattern",
    "solve_oll",
    "solve_pll",
]

#: Where the JSON lookup tables live.
DATA_DIR: Final = Path(__file__).resolve().parents[3] / "data"

#: The four AUF adjustments of the top face, in order.
AUF_MOVES: Final[tuple[tuple[str, ...], ...]] = ((), ("U",), ("U2",), ("U'",))


class LastLayerKind(StrEnum):
    """The two last-layer stages."""

    OLL = "oll"
    PLL = "pll"


@dataclass(frozen=True, slots=True)
class LastLayerCase:
    """One case of one last-layer table.

    Attributes:
        label: The OLL number (``"27"``) or the PLL name (``"T Perm"``).
        name: A longer human readable name.
        algorithm: The algorithm, in canonical notation.
        moves: The algorithm as moves.
    """

    label: str
    name: str
    algorithm: str
    moves: tuple[Move, ...]


@dataclass(frozen=True, slots=True)
class LastLayerResult:
    """The outcome of an OLL or PLL solve.

    Attributes:
        kind: ``"oll"`` or ``"pll"``.
        case: The case that was recognised.
        moves: The moves that perform the stage, including the AUF.
        after: The cube after the stage.
    """

    kind: str
    case: LastLayerCase
    moves: tuple[Move, ...]
    after: Cube

    @property
    def text(self) -> str:
        """Return the stage's moves in canonical notation."""
        return format_moves(self.moves)

    @property
    def label(self) -> str:
        """Return the case label: the OLL number or the PLL name."""
        return self.case.label

    def to_dict(self) -> dict[str, object]:
        """Return a JSON-serializable view of this stage."""
        return {
            "kind": self.kind,
            "label": self.case.label,
            "name": self.case.name,
            "moves": [move.name for move in self.moves],
            "text": self.text,
        }


def oll_pattern(cubie: CubieCube) -> tuple[int, ...]:
    """Return the orientation pattern of the last layer.

    Four corner orientations (0, 1 or 2) followed by four edge orientations
    (0 or 1), all by position.  This is exactly what decides an OLL case.
    """
    return (*cubie.co[:4], *cubie.eo[:4])


def pll_pattern(cubie: CubieCube) -> tuple[int, ...]:
    """Return the full last-layer pattern used to recognise a PLL case.

    The permutations decide the case; the orientations are included as well so that
    an oriented state can never collide with an unoriented one.
    """
    return (*cubie.cp, *cubie.ep, *cubie.co[:4], *cubie.eo[:4])


def _apply(cube: Cube, names: tuple[str, ...]) -> Cube:
    """Apply move names to a cube."""
    return cube.apply_moves(names)


def _case_state(algorithm: tuple[Move, ...]) -> Cube:
    """Return the state that an algorithm solves, by inverting the algorithm."""
    inverse = [move.inverse() for move in reversed(algorithm)]
    return Cube.from_facelets(SOLVED_FACELETS).apply_moves(inverse)


@dataclass(frozen=True, slots=True)
class LastLayerTable:
    """A lookup table of last-layer cases, with recognition built in.

    Attributes:
        kind: ``"oll"`` or ``"pll"``.
        cases: The cases, keyed by label.
        patterns: The recognition map, from pattern to ``(case, auf index)``.
    """

    kind: str
    cases: dict[str, LastLayerCase]
    patterns: dict[tuple[int, ...], tuple[LastLayerCase, int]]

    def recognize(self, cube: Cube) -> tuple[LastLayerCase, int] | None:
        """Return the case of ``cube`` and the AUF needed before its algorithm."""
        pattern = (
            oll_pattern(cube.cubie())
            if self.kind == LastLayerKind.OLL
            else pll_pattern(cube.cubie())
        )
        return self.patterns.get(pattern)


def _load(path: Path) -> list[LastLayerCase]:
    """Read a JSON lookup table."""
    payload = json.loads(path.read_text(encoding="utf-8"))
    cases: list[LastLayerCase] = []
    for entry in payload["cases"]:
        algorithm = str(entry["algorithm"])
        cases.append(
            LastLayerCase(
                label=str(entry["label"]),
                name=str(entry["name"]),
                algorithm=algorithm,
                moves=parse_moves(algorithm),
            )
        )
    return cases


def _solved_by(moves: tuple[Move, ...]) -> Cube:
    """Return the state that ``moves`` solves: the inverse, applied to solved."""
    return Cube.from_facelets(SOLVED_FACELETS).apply_moves(
        [move.inverse() for move in reversed(moves)]
    )


def _entry_rank(entry: tuple[LastLayerCase, int, int]) -> tuple[int, int]:
    """Rank recognition entries, preferring the cleanest stage output."""
    _, pre, post = entry
    return (post != 0, pre + post)


def _build_table(kind: str, path: Path) -> LastLayerTable:
    """Build a table and its recognition map.

    A case is only defined up to an AAF before the algorithm and one after it, so
    every case is stored for all sixteen combinations.  That is what makes the
    tables complete: every last-layer state is solved by *some* ``pre + algorithm +
    post`` sequence.
    """
    cases = {case.label: case for case in _load(path)}
    pattern_of = oll_pattern if kind == LastLayerKind.OLL else pll_pattern
    patterns: dict[tuple[int, ...], tuple[LastLayerCase, int, int]] = {}
    for case in cases.values():
        for pre_index, pre in enumerate(AUF_MOVES):
            for post_index, post in enumerate(AUF_MOVES):
                stage = (
                    *[get_move(name) for name in pre],
                    *case.moves,
                    *[get_move(name) for name in post],
                )
                pattern = pattern_of(_solved_by(stage).cubie())
                entry = (case, pre_index, post_index)
                existing = patterns.get(pattern)
                if existing is not None and existing[0].label != case.label:
                    raise InvalidStateError(
                        "two last-layer cases share a pattern",
                        first=existing[0].label,
                        second=case.label,
                    )
                if existing is None or _entry_rank(entry) < _entry_rank(existing):
                    patterns[pattern] = entry
    return LastLayerTable(kind=kind, cases=cases, patterns=patterns)


@lru_cache(maxsize=1)
def load_oll_table() -> LastLayerTable:
    """Return the OLL table, built from ``data/oll.json``."""
    return _build_table(LastLayerKind.OLL, DATA_DIR / "oll.json")


@lru_cache(maxsize=1)
def load_pll_table() -> LastLayerTable:
    """Return the PLL table, built from ``data/pll.json``."""
    return _build_table(LastLayerKind.PLL, DATA_DIR / "pll.json")


def _solve(cube: Cube, table: LastLayerTable) -> LastLayerResult:
    """Recognise the case of ``cube`` and apply its algorithm."""
    match = table.recognize(cube)
    if match is None:
        raise UnsolvableStateError(
            "the last layer does not match any case in the table",
            kind=table.kind,
        )
    case, pre, post = match
    moves = (
        *[get_move(name) for name in AUF_MOVES[pre]],
        *case.moves,
        *[get_move(name) for name in AUF_MOVES[post]],
    )
    # Wide and slice moves shift the centres, so the display is re-centred: this
    # only changes the point of view, never the puzzle.
    after = cube.apply_moves(moves).normalized()
    return LastLayerResult(kind=table.kind, case=case, moves=moves, after=after)


def solve_oll(cube: Cube) -> LastLayerResult:
    """Orient the last layer, reporting which of the 57 cases it was."""
    return _solve(cube, load_oll_table())


def solve_pll(cube: Cube) -> LastLayerResult:
    """Permute the last layer, reporting which of the 21 cases it was."""
    return _solve(cube, load_pll_table())
